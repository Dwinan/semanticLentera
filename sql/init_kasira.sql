CREATE TABLE produk_jual (
    barcode VARCHAR(20) PRIMARY KEY,
    nama_produk VARCHAR(100) NOT NULL,
    harga_jual VARCHAR(30) NOT NULL,
    kode_kategori VARCHAR(20)
);

CREATE TABLE transaksi (
    id VARCHAR(15) PRIMARY KEY,
    tanggal VARCHAR(20) NOT NULL,
    nama_kasir VARCHAR(60)
);

CREATE TABLE item_transaksi (
    id SERIAL PRIMARY KEY,
    id_transaksi VARCHAR(15) NOT NULL REFERENCES transaksi(id),
    barcode VARCHAR(20) NOT NULL REFERENCES produk_jual(barcode),
    qty INTEGER NOT NULL
);

